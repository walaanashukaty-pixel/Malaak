class DemoMalaakService {
  const DemoMalaakService._();

  static String reply(String input) {
    final text = input.trim();
    if (text.isEmpty) return 'احكيلي بجملة واحدة شو صار، وأنا بساعدك نرتب البداية.';

    if (_containsAny(text, ['اضرب', 'أكسر', 'انفجر', 'معصبة', 'غضب', 'بدي أئذي', 'بدي أؤذي'])) {
      return 'أولويتنا الآن الأمان، مو تحليل المشكلة. إذا في احتمال تأذي نفسك أو حدا، ابعدي عن التصعيد والأشياء اللي ممكن تسبب أذى واطلبي دعمًا بشريًا مباشرًا. إذا ما في خطر مباشر: كم مستوى الشدة من 0 لـ10؟';
    }

    if (_containsAny(text, ['ما رد', 'بيحبني', 'ما عاد يحبني', 'يتركني', 'تركني'])) {
      return 'واضح إن الموقف حرّك خوف قوي. ما بقدر أعرف شو عم يشعر الطرف الثاني من عدم الرد وحده. خلينا نفصل الحقائق عن التفسير: شو صار فعليًا، وشو القصة اللي عقلك كملها؟';
    }

    if (_containsAny(text, ['بفكر', 'تفكير', 'راسي', 'شو لو', 'ما عم بوقف'])) {
      return 'خلينا نعرف شو نوع التفكير قبل ما نحاول نوقفه. هل في مشكلة محددة تقدري تعملي تجاهها خطوة، ولا عم نعيد نفس السؤال بدون معلومة جديدة؟';
    }

    if (_containsAny(text, ['زوجي', 'تخانقنا', 'خلاف', 'زعلان'])) {
      return 'قبل ما نقرر شو تحكي، خلينا نفهم الدائرة: شو صار بكاميرا؟ شو حسّيتي؟ شو عملتي؟ وشو عمل هو بعدها؟';
    }

    if (_containsAny(text, ['تعبانة', 'منهارة', 'فوضى', 'كل شي'])) {
      return 'يمكن ما نحتاج نحل شخصيتك اليوم. خلينا نرتب الحمل: شو الشي الوحيد اللي لازم الآن، شو ممكن يتأجل، وشو خارج سيطرتك؟';
    }

    return 'سمعتك. بدك مني هلأ أساعدك تهدي، نفهم اللي صار، ولا نقرر شو تعملي؟';
  }

  static bool _containsAny(String text, List<String> words) {
    return words.any(text.contains);
  }
}
